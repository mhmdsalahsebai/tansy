// Copies the provider and model icons the dashboard shows from @lobehub/icons-static-svg
// into icons.generated.ts, so the plugin needs no SVG loader and no icon package at run time.
// Run after upgrading the icons: node plugins/ai/scripts/icons.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const root = path.join(path.dirname(require.resolve("@lobehub/icons-static-svg/package.json")), "icons");
const version = JSON.parse(readFileSync(path.join(root, "..", "package.json"), "utf8")).version;

const NAMES = [
  "openai", "claude", "anthropic", "gemini", "gemma", "google", "vercel", "mistral", "xai", "grok", "groq", "deepseek", "openrouter", "opencode", "commandcode",
  "ollama", "lmstudio", "vllm", "meta", "qwen", "kimi", "moonshot", "zhipu", "chatglm", "minimax", "cohere", "microsoft", "nvidia",
  "perplexity", "flux", "bfl", "stability", "ideogram", "recraft", "dalle", "midjourney", "huggingface", "together", "fireworks",
  "cerebras", "amazon", "bedrock", "nova", "ai21", "yi", "baichuan", "hunyuan", "doubao", "bytedance", "stepfun", "internlm",
  "liquid", "nousresearch", "inflection", "reka", "wenxin", "spark", "zai", "luma", "runway", "kling", "hailuo", "sora",
];

const icons = {};
for (const name of NAMES) {
  const color = path.join(root, `${name}-color.svg`);
  const mono = path.join(root, `${name}.svg`);
  const file = existsSync(color) ? color : existsSync(mono) ? mono : null;
  if (!file) continue;
  const svg = readFileSync(file, "utf8").replace(/<title>[^<]*<\/title>/, "").replace(/\s+style="[^"]*"/, "").replace(/\s+/g, " ").trim();
  icons[name] = { svg, mono: file === mono };
}

const body = `// Generated by scripts/icons.mjs from @lobehub/icons-static-svg ${version} (MIT). Don't edit by hand.
/** Each icon's SVG, and whether it is one colour (currentColor), which then follows the text. */
export const ICONS: Record<string, { svg: string; mono: boolean }> = ${JSON.stringify(icons, null, 0).replace(/},"/g, '},\n  "').replace(/^{"/, '{\n  "').replace(/}}$/, "},\n}")};
`;
writeFileSync(path.join(here, "..", "icons.generated.ts"), body);
console.log(`Wrote ${Object.keys(icons).length} icons.`);
