type Words = typeof messages.en;

/** The invitation email, in the invitee's language. */
const mail = {
  en: {
    subject: "You're invited to {tenant}",
    body: "{inviter} invited you to work on {tenant}. Sign in with this email address to accept. The invitation lasts {days} days.",
    action: "Accept the invitation",
  },
  ar: {
    subject: "دعوة للانضمام إلى {tenant}",
    body: "دعاك {inviter} للعمل على {tenant}. سجّل الدخول بعنوان البريد هذا لقبول الدعوة. تبقى الدعوة صالحة {days} يومًا.",
    action: "اقبل الدعوة",
  },
};

/** The invitation email's words in a language, English where there are none, with the language they're in. */
export function invitationMail(locale: string | null | undefined, values: { tenant: string; inviter: string; days: number }) {
  const language = locale && locale.split("-")[0] in mail ? (locale.split("-")[0] as keyof typeof mail) : "en";
  const fill = (text: string) => text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name as keyof typeof values] ?? ""));
  const words = mail[language];
  return { locale: language, subject: fill(words.subject), body: fill(words.body), action: words.action };
}

/** One of the plugin's top-level words in a language, for the few a route answers with itself. English where missing. */
export function wordIn(locale: string | null | undefined, key: "switcherNone"): string {
  const words = (locale && (messages as Record<string, Partial<Words>>)[locale]) || messages.en;
  return words[key] ?? messages.en[key];
}
