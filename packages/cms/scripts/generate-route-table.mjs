/**
 * Writes the route tables in routes/ from the route and page files under app/.
 * tests/contract fails if the table and the files disagree, so run this after adding or removing a route.
 */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

const HEADER = "// Generated by scripts/generate-route-table.mjs. Don't edit.\n";

function filesNamed(dir, name) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? filesNamed(full, name) : entry.name === name ? [full] : [];
  });
}

/** Folder of each file, relative to base, in a stable order. */
const patterns = (base, name) => filesNamed(path.join(root, base), name).map((file) => path.relative(path.join(root, base), path.dirname(file)).replaceAll(path.sep, "/")).sort();
const write = (name, body) => writeFileSync(path.join(root, "routes", name), HEADER + body);
const str = JSON.stringify;

const importPath = (base, pattern, file) => `../${base}/${pattern ? `${pattern}/` : ""}${file}`;
const tableRows = (base, file) => (pattern) => `  { pattern: ${str(pattern)}, load: () => import(${str(importPath(base, pattern, file))}) },`;

write("api-table.generated.ts", `export const apiRoutes: ReadonlyArray<{ pattern: string; load: () => Promise<Record<string, unknown>> }> = [
${patterns("app/api", "route.ts").map(tableRows("app/api", "route")).join("\n")}
];
`);

const PAGE_TABLE = "ReadonlyArray<{ pattern: string; load: () => Promise<{ default: unknown }> }>";

write("pages-table.generated.ts", `export const dashboardPages: ${PAGE_TABLE} = [
${patterns("app/dashboard", "page.tsx").map(tableRows("app/dashboard", "page")).join("\n")}
];

export const authPages: ${PAGE_TABLE} = [
${patterns("app/auth", "page.tsx").map(tableRows("app/auth", "page")).join("\n")}
];
`);

// Client components a page renders that aren't a page.client.tsx of its own.
const SHARED = { RecordForm: "../components/collections/RecordForm", ViewForm: "../components/collections/ViewForm", BlockTypeForm: "../components/blocks/BlockTypeForm" };
const clientRows = [
  ...patterns("app/dashboard", "page.client.tsx").map((pattern) => [pattern, importPath("app/dashboard", pattern, "page.client")]),
  ...Object.entries(SHARED),
];

write("client-pages.generated.tsx", `"use client";

import dynamic from "next/dynamic";
import { createElement, type ComponentType } from "react";

export type ClientPageName =
${clientRows.map(([name]) => `  | ${str(name)}`).join("\n")};

// Typed by name, so the published declarations don't have to spell out each page's private props.
const pages = {
${clientRows.map(([name, target]) => `  ${str(name)}: dynamic(() => import(${str(target)})),`).join("\n")}
} as unknown as Record<ClientPageName, ComponentType<object>>;

export function ClientPageSwitch({ name, props }: { name: ClientPageName; props: object }) {
  return createElement(pages[name], props);
}
`);
