export type ByteStream = ReadableStream<Uint8Array>;

/** Both ends inclusive, as in an HTTP Range header. */
export interface ByteRange {
  start: number;
  end: number;
}

export interface PutOptions {
  size: number;
  contentType: string;
}

/** One object, as `list` reports it. */
export interface StoredObject {
  key: string;
  size: number;
}

export interface SignedUrlOptions {
  /** Seconds. */
  expiresIn: number;
  contentType: string;
  disposition: string;
}

export interface ThumbnailOptions {
  width: number;
  /** Absent for a thumbnail that keeps the image's shape. */
  height?: number;
  /** "cover" crops to exactly width by height. "inside" fits within width. Neither enlarges a smaller image. */
  fit: "cover" | "inside";
  /**
   * Where the subject of the picture is, as whole percentages from the left and from the top,
   * for a "cover" thumbnail that has to crop. Absent means the middle. An adapter whose image
   * service can't be told where to crop may ignore it, and then crops from the middle as before.
   */
  focus?: { x: number; y: number };
  /** Seconds. Only binding when `thumbnailUrlsExpire` is set. */
  expiresIn: number;
}

/**
 * Moves bytes and nothing else. Access checks, file records, keys, type
 * detection and thumbnails all live in core/files, so an adapter can't weaken
 * them. Keys are generated by core and never contain user input.
 */
export interface StorageAdapter {
  /** Stored on each file, so it must stay the same for as long as files live here. */
  readonly name: string;
  /** Throws if this adapter must not run in the current environment. Checked at startup and before use. */
  assertUsable?(): void;
  put(key: string, body: ByteStream, options: PutOptions): Promise<void>;
  /** Null when the object doesn't exist. */
  get(key: string, range?: ByteRange): Promise<ByteStream | null>;
  /** Succeeds when the object is already gone. */
  delete(key: string): Promise<void>;
  /**
   * Lets clients fetch from the provider directly. Without it, the CMS streams the file itself.
   * Only for providers that serve the given content type and disposition, which keep a file
   * a browser could run from rendering, and that stop the URL working after `expiresIn`.
   */
  signedUrl?(key: string, options: SignedUrlOptions): Promise<string>;
  /**
   * Hands thumbnails to the provider's image service, for a raster image stored under `key`.
   * The URL must serve that image resized as asked, in any raster format. Core then neither
   * renders nor stores thumbnails for this adapter.
   */
  thumbnailUrl?(key: string, options: ThumbnailOptions): Promise<string>;
  /**
   * Set when thumbnailUrl's URLs stop working after `expiresIn`. Core then sends clients to
   * them. Otherwise it fetches the thumbnail itself, so a URL that never expires stays on the server.
   */
  readonly thumbnailUrlsExpire?: boolean;
  /** Every object whose key starts with `prefix`, in any order. Backups need it to find and prune archives. */
  list?(prefix: string): Promise<StoredObject[]>;
}

export interface StorageConfig {
  /** Where new uploads go. */
  adapter: StorageAdapter;
  /** Adapters that still hold older files after a move. Read and delete only. */
  previous?: StorageAdapter[];
  /** Largest accepted upload in bytes. Defaults to 50 MiB. */
  maxUploadBytes?: number;
}
