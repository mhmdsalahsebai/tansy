import { z } from "zod";
import type { Principal } from "../authz/principal";
import type { CollectionWithFields } from "../content/access";
import { readableFields } from "../content/records";
import { getFieldDefinition } from "../fields/registry";
import { apiPath } from "../../lib/paths";
import { isLocalizedCollection, isLocalizedField } from "../i18n/context";

type JsonSchema = Record<string, unknown> & { type?: string | string[]; enum?: unknown[]; const?: unknown; items?: JsonSchema; properties?: Record<string, JsonSchema>; required?: string[]; anyOf?: JsonSchema[]; oneOf?: JsonSchema[]; additionalProperties?: boolean | JsonSchema };

type Field = CollectionWithFields["fields"][number];

/** The JSON Schema of a field's value, from the same definition the server validates with. */
export function fieldSchema(field: Pick<Field, "type" | "config">): JsonSchema {
  const config = (field.config ?? {}) as Record<string, unknown>;
  try {
    const schema = z.toJSONSchema(getFieldDefinition(field.type).value(config), { unrepresentable: "any", io: "input" }) as JsonSchema;
    delete schema.$schema;
    return schema;
  } catch {
    return {};
  }
}

const isRequired = (field: Pick<Field, "config">) => (field.config as { required?: boolean } | null)?.required === true;

const SYSTEM_PROPERTIES: Record<string, JsonSchema> = {
  id: { type: "integer" },
  status: { type: "string" },
  createdAt: { type: "string" },
  updatedAt: { type: "string" },
  publishedAt: { type: ["string", "null"] },
  createdById: { type: ["string", "null"] },
};

export function toTsType(schema: JsonSchema): string {
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map(toTsType).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((type) => toTsType({ ...schema, type })).join(" | ");
  switch (schema.type) {
    case "string": return "string";
    case "number":
    case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return schema.items ? `Array<${toTsType(schema.items)}>` : "unknown[]";
    case "object": {
      if (!schema.properties) return "Record<string, unknown>";
      const entries = Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${toTsType(value)}`);
      return `{ ${entries.join("; ")} }`;
    }
    default: return "unknown";
  }
}

const pascal = (slug: string) => slug.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("").replace(/^(\d)/, "C$1");

const blockTypeName = (name: string) => `Block${name.split(/[-_]/).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("")}`;

type BlockShape = { name: string; fields: unknown };
type FieldShape = Pick<Field, "type" | "config">;

/** A stream field is a list of the generated block types, and everything else comes from its value schema. */
function fieldTsType(field: FieldShape, blocks: BlockShape[]) {
  if (field.type !== "stream") return toTsType(fieldSchema(field));
  const allowed = (field.config as { allowedBlocks?: string[] } | null)?.allowedBlocks;
  const names = blocks.map((block) => block.name).filter((name) => !allowed?.length || allowed.includes(name));
  return names.length ? `Array<${names.map(blockTypeName).join(" | ")}>` : "unknown[]";
}

function blockLines(blocks: BlockShape[]) {
  const lines = blocks.flatMap((block) => {
    const fields = block.fields as Array<FieldShape & { name: string }>;
    const value = fields.map((field) => `${JSON.stringify(field.name)}${isRequired(field) ? "" : "?"}: ${fieldTsType(field, blocks)}`).join("; ");
    return [`export interface ${blockTypeName(block.name)} {`, "  id: string;", `  type: ${JSON.stringify(block.name)};`, "  v: number;", `  value: { ${value} };`, "}", ""];
  });
  return blocks.length ? [...lines, `export type CmsBlock = ${blocks.map((block) => blockTypeName(block.name)).join(" | ")};`, ""] : lines;
}

/** TypeScript for what this principal can read. Hidden fields are left out unless they hold record:read. */
export function generateTypes(collections: CollectionWithFields[], principal: Principal, blocks: BlockShape[] = []) {
  const lines = [
    "// Generated by tansy. Do not edit.",
    "",
    "export interface CmsRecord {",
    "  id: number;",
    "  status: string;",
    "  createdAt: string;",
    "  updatedAt: string | null;",
    "  publishedAt: string | null;",
    "  createdById: string | null;",
    "  /** For a localized collection, the language this record was read in. */",
    "  locale?: string;",
    "}",
    "",
    "/** A localized field read with locale=*, by language code. */",
    "export type Localized<T> = Record<string, T>;",
    "",
    ...blockLines(blocks),
  ];
  for (const collection of collections) {
    const fields = readableFields(collection, principal);
    lines.push(`export interface ${pascal(collection.slug)} extends CmsRecord {`);
    for (const field of fields) lines.push(`  ${field.name}: ${fieldTsType(field, blocks)}${isRequired(field) ? "" : " | null"};`);
    lines.push("}", "");
    if (isLocalizedCollection(collection)) {
      // locale=*: every language of each localized field at once.
      const localized = fields.filter((field) => isLocalizedField(collection, field));
      lines.push(`export interface ${pascal(collection.slug)}AllLocales extends Omit<${pascal(collection.slug)}, ${localized.map((field) => JSON.stringify(field.name)).join(" | ") || "never"}> {`);
      for (const field of localized) lines.push(`  ${field.name}: Localized<${fieldTsType(field, blocks)} | null>;`);
      lines.push("  locales: string[];", "  statuses: Record<string, string>;", "}", "");
    }
  }
  lines.push("export interface CmsCollections {");
  for (const collection of collections) lines.push(`  ${JSON.stringify(collection.slug)}: ${pascal(collection.slug)};`);
  lines.push("}", "");
  return lines.join("\n");
}

const json = (schema: JsonSchema) => ({ "application/json": { schema } });
const ref = (slug: string): JsonSchema => ({ $ref: `#/components/schemas/${pascal(slug)}` });
const parameter = (name: string, schema: JsonSchema, description: string) => ({ name, in: "query", required: false, schema, description });

const LOCALE_PARAMETERS = [
  parameter("locale", { type: "string" }, "For a localized collection, the language to read, or * for every language with each localized field as a map by language. Others ignore it. An unknown language is a 400 INVALID_LOCALE."),
  parameter("fallback", { enum: ["chain", "none"] }, "none reads only the language asked for. chain, the default, falls back along its chain to a published translation."),
];
const VIEW_PARAMETERS = [
  ...LOCALE_PARAMETERS,
  parameter("expand", { type: "string" }, "Relations to expand, comma separated. Each expanded record must pass its own view rule."),
  parameter("fields", { type: "string" }, "Fields to return, comma separated."),
];
const LIST_PARAMETERS = [
  parameter("page", { type: "integer", minimum: 1 }, "Page number."),
  parameter("perPage", { type: "integer", minimum: 1, maximum: 200 }, "Records per page."),
  parameter("sort", { type: "string" }, "Fields to sort by, with - for descending."),
  parameter("filter", { type: "string" }, "Filter expression, always combined with the collection's list rule. It may follow one relation, as in author.name = \"Ada\", or backwards as <slug>_via_<field>.title ?= \"x\"."),
  parameter("skipTotal", { type: "boolean" }, "Skip counting matches."),
  parameter("search", { type: "string" }, "Words to find in the searchable fields."),
  ...VIEW_PARAMETERS,
];
const ID = { name: "id", in: "path", required: true, schema: { type: "integer" } };
const ERRORS = { "400": { description: "Invalid request" }, "403": { description: "Locked" }, "404": { description: "Not found" } };

/** An OpenAPI 3.1 description of the record API on this instance. */
export function generateOpenApi(collections: CollectionWithFields[], principal: Principal, serverUrl: string) {
  const schemas: Record<string, JsonSchema> = {};
  const paths: Record<string, unknown> = {};
  for (const collection of collections) {
    const fields = readableFields(collection, principal);
    const name = pascal(collection.slug);
    const values = Object.fromEntries(fields.map((field) => [field.name, fieldSchema(field)]));
    schemas[name] = { type: "object", properties: { ...SYSTEM_PROPERTIES, ...(isLocalizedCollection(collection) ? { locale: { type: "string", description: "The language this record was read in." } } : {}), ...values } };
    if (isLocalizedCollection(collection)) {
      const localized = Object.fromEntries(fields.filter((field) => isLocalizedField(collection, field)).map((field) => [field.name, { type: "object", additionalProperties: fieldSchema(field), description: "By language code." }]));
      schemas[`${name}AllLocales`] = { type: "object", description: "The record read with locale=*.", properties: { ...SYSTEM_PROPERTIES, ...values, ...localized, locales: { type: "array", items: { type: "string" } }, statuses: { type: "object", additionalProperties: { type: "string" } } } };
    }
    const tags = [collection.slug];
    const input: JsonSchema = { type: "object", properties: { status: { enum: ["draft", "published"] }, ...values }, additionalProperties: false };
    const one = { description: "The record", content: json(ref(collection.slug)) };
    const base = apiPath(`/collections/${collection.slug}/records`);
    const writable = collection.type !== "view";
    paths[base] = {
      get: { tags, operationId: `list${name}`, parameters: LIST_PARAMETERS, responses: { "200": { description: "A page of records", content: json({ type: "object", properties: { page: { type: "integer" }, perPage: { type: "integer" }, totalItems: { type: "integer" }, totalPages: { type: "integer" }, items: { type: "array", items: ref(collection.slug) } } }) }, ...ERRORS } },
      ...(writable ? { post: { tags, operationId: `create${name}`, parameters: LOCALE_PARAMETERS.slice(0, 1), requestBody: { required: true, content: json(input) }, responses: { "200": one, ...ERRORS } } } : {}),
    };
    paths[`${base}/{id}`] = {
      get: { tags, operationId: `get${name}`, parameters: [ID, ...VIEW_PARAMETERS], responses: { "200": one, ...ERRORS } },
      ...(writable ? {
        patch: { tags, operationId: `update${name}`, parameters: [ID, ...LOCALE_PARAMETERS.slice(0, 1)], requestBody: { required: true, content: json(input) }, responses: { "200": one, ...ERRORS } },
        delete: { tags, operationId: `delete${name}`, parameters: [ID], responses: { "204": { description: "Deleted" }, ...ERRORS } },
      } : {}),
    };
  }
  return {
    openapi: "3.1.0",
    info: { title: "tansy record API", version: "1" },
    servers: [{ url: serverUrl }],
    security: [{ apiKey: [] }, {}],
    paths,
    components: { schemas, securitySchemes: { apiKey: { type: "apiKey", in: "header", name: "x-api-key" } } },
  };
}
