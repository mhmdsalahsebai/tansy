/**
 * Writes the metadata every published plugin and theme needs, from one place:
 *
 *   node scripts/package-metadata.mjs [--check]
 *
 * - `files`, so a publish ships the package and nothing else that happens to be in the folder.
 * - `README.md`, so the npm page says what the package is and where its documentation is.
 * - `peerDependencies` ranges that mean something: `*` lets a bad pairing install silently.
 *
 * `--check` changes nothing and exits 1 with the list of what is out of date;
 * `tests/unit/package-metadata.test.ts` runs the same comparison.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT, extensionPackages, peerRangeFor, publishedPackages } from "./workspace-packages.mjs";

const GENERATED = "<!-- Generated by scripts/package-metadata.mjs. Change that script, not this file. -->";
const REPO = "https://github.com/mhmdsalahsebai/tansy";
const DOCS = `${REPO}/blob/main`;

/** Source that belongs in a tarball, as globs rather than one line per file. */
const SHIPPED = ["*.ts", "*.tsx", "*.css", "*.woff", "*.woff2"];
/** Folders that exist to build the package, not to ship in it. */
const NOT_SHIPPED = new Set(["scripts", "node_modules", "dist", "tests"]);

const names = (dir) => readdirSync(path.join(ROOT, dir));

/** What `files` should hold: the globs that match something, the folders that ship, then the two files npm shows. */
export function filesFor({ folder }) {
  const entries = names(folder);
  const globs = SHIPPED.filter((glob) => entries.some((name) => name.endsWith(glob.slice(1))));
  const folders = entries.filter((name) => statSync(path.join(ROOT, folder, name)).isDirectory() && !NOT_SHIPPED.has(name)).sort();
  const data = entries.filter((name) => name.endsWith(".json") && name !== "package.json").sort();
  return [...globs, ...data, ...folders, "LICENSE", "README.md"];
}

/** Families whose adapters are documented in a guide, because core owns the feature rather than a plugin. */
const FAMILY_GUIDES = { search: "docs/guides/search.md", storage: "docs/guides/storage.md" };

/** The documentation page that explains this package: its own, its family's, or the guide for its kind. */
function documentation({ folder, slug, kind }) {
  const own = `docs/${kind === "theme" ? "themes" : "plugins"}/${slug}.md`;
  if (existsSync(path.join(ROOT, own))) return { file: own, label: `the ${slug} ${kind} documentation` };
  // A provider package, such as email-resend, is documented on the page of the plugin it serves.
  const family = slug.split("-")[0];
  const familyPage = `docs/plugins/${family}.md`;
  if (kind === "plugin" && family !== slug && existsSync(path.join(ROOT, familyPage))) return { file: familyPage, label: `the ${family} plugin documentation` };
  // A search or storage adapter serves a core feature, so its documentation is that feature's guide.
  if (kind === "plugin" && family !== slug && FAMILY_GUIDES[family]) return { file: FAMILY_GUIDES[family], label: `the ${family} guide` };
  if (kind === "theme") return { file: "docs/guides/themes.md", label: "the themes guide" };
  return { file: "docs/guides/plugins.md", label: "the plugins guide" };
}

export function readmeFor(pkg) {
  const { name, description } = pkg.manifest;
  const { file, label } = documentation(pkg);
  const what = pkg.kind === "theme" ? "theme" : "plugin";
  return `${GENERATED}

# ${name}

${description}

\`\`\`bash
npm install ${name}
\`\`\`

Add it to \`tansy.config.ts\`. See [${label}](${DOCS}/${file}) for what it adds and the options it takes.

A first-party ${what} for [tansy](${REPO}), a self-hosted, runtime-schema CMS for Next.js. MIT licensed.
`;
}

/** The same peers the manifest already declares, with a range instead of `*`. */
export function peersFor({ manifest }) {
  const peers = manifest.peerDependencies ?? {};
  return Object.fromEntries(Object.keys(peers).sort().map((name) => [name, peerRangeFor(name) ?? peers[name]]));
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/** Everything this script owns, for one package, so a check and a write can't disagree. */
export function metadataFor(pkg) {
  return { files: filesFor(pkg), readme: readmeFor(pkg), peerDependencies: peersFor(pkg) };
}

/** What is out of date, for the check and for the test. */
export function outOfDate(pkg) {
  const wanted = metadataFor(pkg);
  const readme = path.join(ROOT, pkg.folder, "README.md");
  const problems = [];
  if (!same(pkg.manifest.files, wanted.files)) problems.push("files");
  if (!same(pkg.manifest.peerDependencies, wanted.peerDependencies)) problems.push("peerDependencies");
  if (!existsSync(readme) || readFileSync(readme, "utf8") !== wanted.readme) problems.push("README.md");
  return problems;
}

/** The licence file npm needs inside the tarball to show the licence at all. */
function licence(pkg) {
  const file = path.join(ROOT, pkg.folder, "LICENSE");
  const root = readFileSync(path.join(ROOT, "LICENSE"), "utf8");
  return { file, ok: existsSync(file) && readFileSync(file, "utf8") === root, content: root };
}

/**
 * Keys in the order npm's own docs put them, so a diff of a manifest stays readable
 * and a new key never lands in the middle of the dependencies.
 */
const ORDER = ["name", "version", "description", "keywords", "license", "author", "homepage", "repository", "bugs", "type", "bin", "exports", "files", "engines", "scripts", "peerDependencies", "dependencies", "devDependencies"];

function writeManifest(folder, manifest) {
  const ordered = {};
  for (const key of ORDER) if (key in manifest) ordered[key] = manifest[key];
  for (const key of Object.keys(manifest)) if (!(key in ordered)) ordered[key] = manifest[key];
  writeFileSync(path.join(ROOT, folder, "package.json"), `${JSON.stringify(ordered, null, 2)}\n`);
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const pkg of extensionPackages()) {
    const problems = outOfDate(pkg);
    const file = licence(pkg);
    if (!file.ok) problems.push("LICENSE");
    if (!problems.length) continue;
    if (check) {
      stale.push(`${pkg.folder}: ${problems.join(", ")}`);
      continue;
    }
    const wanted = metadataFor(pkg);
    writeManifest(pkg.folder, { ...pkg.manifest, files: wanted.files, peerDependencies: wanted.peerDependencies });
    writeFileSync(path.join(ROOT, pkg.folder, "README.md"), wanted.readme);
    if (!file.ok) writeFileSync(file.file, file.content);
    console.log(`${pkg.folder}: wrote ${problems.join(", ")}`);
  }
  // The two packages with a shape of their own still need the licence in their tarball.
  for (const pkg of publishedPackages().filter(({ builder }) => builder !== "tsc")) {
    const file = licence(pkg);
    if (file.ok) continue;
    if (check) stale.push(`${pkg.folder}: LICENSE`);
    else {
      writeFileSync(file.file, file.content);
      console.log(`${pkg.folder}: wrote LICENSE`);
    }
  }
  if (!stale.length) return console.log(check ? "Every published package's metadata is up to date." : "Done.");
  console.error(`Out of date. Run node scripts/package-metadata.mjs:\n${stale.map((line) => `  ${line}`).join("\n")}`);
  process.exit(1);
}

if (process.argv[1] === import.meta.filename) main();
